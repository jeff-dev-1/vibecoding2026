const DICT: Record<Lang, Partial<Record<Key, string>>> = {
  "zh-Hans": ZH_HANS,
  "zh-Hant": ZH_HANT,
  en: EN,
};

/** <html lang> 要的是 BCP 47 标签, 和我们内部的 id 不完全一样。 */
const HTML_LANG: Record<Lang, string> = {
  "zh-Hans": "zh-Hans",
  "zh-Hant": "zh-Hant",
  en: "en",
};

const STORAGE_KEY = "alad-lang";

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }>({
  lang: "zh-Hans",
  setLang: () => undefined,
  t: (k) => ZH_HANS[k],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("zh-Hans");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && DICT[saved]) setLang(saved);
  }, []);

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = HTML_LANG[lang];
  }, [lang]);

  // 缺翻译时回落简体而不是把 key 打出来: 漏译应该读起来像"还没翻", 而不是像坏了。
  const t = (k: Key) => DICT[lang][k] ?? ZH_HANS[k];
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
